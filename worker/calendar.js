const WD = ['일', '월', '화', '수', '목', '금', '토'];
const iso = (d) => d.toISOString().slice(0, 10);

/** 그 달의 n번째 요일(0 일 … 6 토). 없으면 null */
function nthWeekday(y, m, wd, n) {
  const first = new Date(Date.UTC(y, m - 1, 1));
  const day = 1 + ((wd - first.getUTCDay() + 7) % 7) + (n - 1) * 7;
  const d = new Date(Date.UTC(y, m - 1, day));
  return d.getUTCMonth() === m - 1 ? iso(d) : null;
}

/** 계산으로 나오는 일정. 한국 옵션 만기 둘째 목요일 · 미국 옵션 만기 셋째 금요일 */
export function ruleEvents(fromISO, months = 4) {
  const [y0, m0] = fromISO.split('-').map(Number);
  const out = [];
  for (let i = 0; i < months; i++) {
    const mm = ((m0 - 1 + i) % 12) + 1;
    const yy = y0 + Math.floor((m0 - 1 + i) / 12);
    const quad = [3, 6, 9, 12].includes(mm);
    const kr = nthWeekday(yy, mm, 4, 2);
    const us = nthWeekday(yy, mm, 5, 3);
    if (kr) out.push([kr, 'expiry', quad ? '선물·옵션 동시만기' : '옵션 만기일', quad ? '네 마녀의 날 · 변동성 큼' : '만기 전후 수급 출렁임']);
    if (us) out.push([us, 'expiry', '미국 옵션 만기', '']);
  }
  return out;
}

/** 오늘(한국 날짜 ISO)부터 앞으로 limit 개 */
export function buildCalendar(todayISO, limit = 8) {
  const t0 = Date.parse(todayISO + 'T00:00:00Z');
  const seen = new Set();
  const rows = [];
  const all = EVENTS.concat(ruleEvents(todayISO)).sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  for (const [date, kind, title, note] of all) {
    const dday = Math.round((Date.parse(date + 'T00:00:00Z') - t0) / 86400000);
    if (dday < 0) continue;
    const key = date + title;
    if (seen.has(key)) continue;
    seen.add(key);
    const d = new Date(date + 'T00:00:00Z');
    rows.push({
      date, kind, title, note, dday,
      label: `${d.getUTCMonth() + 1}월 ${d.getUTCDate()}일 (${WD[d.getUTCDay()]})`,
      dtext: dday === 0 ? '오늘' : dday === 1 ? '내일' : 'D-' + dday,
    });
    if (rows.length >= limit) break;
  }
  return rows;
}
